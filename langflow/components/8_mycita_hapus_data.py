# ---------------------------- myCITA HAPUS -----------------------------
class MyCITAHapusData(Component):
    display_name = "myCITA Hapus Data"
    description = (
        "Menghapus SELURUH data pengguna myCITA (profil, keuangan, target, hasil analisis) secara permanen. "
        "Hanya panggil jika pengguna secara eksplisit meminta datanya dihapus. Input JSON "
        "{'user_id': ..., 'konfirmasi': true}."
    )
    icon = "trash-2"
    name = "MyCITAHapusData"

    inputs = [
        MessageTextInput(
            name="input_json",
            display_name="Permintaan Hapus (JSON)",
            info='{"user_id": "budi", "konfirmasi": true}',
            tool_mode=True,
        ),
        StrInput(name="db_path", display_name="Lokasi Database", value="", advanced=True,
                 info="Kosongkan untuk memakai ~/.mycita/mycita.db. Harus sama di semua komponen myCITA."),
    ]
    outputs = [Output(display_name="Hasil", name="hasil", method="hapus_data_mycita")]

    def hapus_data_mycita(self) -> Message:
        try:
            data = parse_input(self.input_json)
            uid = norm_user_id(data)
            if data.get("konfirmasi") is not True and str(data.get("konfirmasi")).lower() not in ("true", "ya", "yes"):
                payload = {"status": "butuh_konfirmasi", "user_id": uid,
                           "pesan": "Penghapusan permanen membutuhkan 'konfirmasi': true dari pengguna."}
            else:
                n = hapus_semua_data(uid, self.db_path)
                payload = {"status": "ok", "user_id": uid,
                           "pesan": f"{n} catatan milik '{uid}' telah dihapus permanen."}
        except Exception as e:  # noqa: BLE001
            payload = galat(str(e))
        return hasil_message(self, payload)
